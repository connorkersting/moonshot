WITH source_subagents AS (
    SELECT
        subagent_id,
        description,
        agent_role,
        agent_type,
        requested_model,
        actual_models,
        spawn_id,
        spawn_linked,
        spawn_depth,
        first_ts_utc,
        last_ts_utc,
        duration_s,
        session_part,
        n_messages,
        n_jsonl_lines,
        n_tool_calls,
        n_messages_usage_final,
        input_tokens,
        output_tokens_final_only,
        output_tokens_lower_bound,
        cache_creation_tokens,
        cache_read_tokens,
    FROM {{ source('moonshot_raw', 'subagents') }}
),

renamed_subagents AS (
    SELECT
        subagent_id,
        description AS spawn_description,
        agent_role,
        agent_type,
        requested_model AS requested_model_alias,
        actual_models AS actual_model_ids,
        spawn_id,
        spawn_linked AS is_spawn_linked,
        spawn_depth,
        CAST(REPLACE(first_ts_utc, 'Z', '') AS TIMESTAMP) AS first_request_at_utc,
        CAST(REPLACE(last_ts_utc, 'Z', '') AS TIMESTAMP) AS last_request_at_utc,
        duration_s,
        CAST(session_part AS INTEGER) AS session_part,
        n_messages,
        n_jsonl_lines,
        n_tool_calls,
        n_messages_usage_final,
        input_tokens,
        output_tokens_final_only,
        output_tokens_lower_bound,
        cache_creation_tokens,
        cache_read_tokens,
    FROM source_subagents
)

SELECT
    subagent_id,
    spawn_description,
    agent_role,
    agent_type,
    requested_model_alias,
    actual_model_ids,
    spawn_id,
    is_spawn_linked,
    spawn_depth,
    first_request_at_utc,
    last_request_at_utc,
    duration_s,
    session_part,
    n_messages,
    n_jsonl_lines,
    n_tool_calls,
    n_messages_usage_final,
    input_tokens,
    output_tokens_final_only,
    output_tokens_lower_bound,
    cache_creation_tokens,
    cache_read_tokens,
FROM renamed_subagents
