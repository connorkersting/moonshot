WITH source_messages AS (
    SELECT
        message_id,
        request_id,
        session_id,
        agent_id,
        is_subagent,
        agent_role,
        model,
        ts_utc,
        ts_local,
        session_part,
        input_tokens,
        output_tokens,
        output_tokens_lower_bound,
        usage_final,
        cache_creation_tokens,
        cache_read_tokens,
        thinking_tokens,
        stop_reason,
        tool_names,
        n_tool_calls,
        n_jsonl_lines,
    FROM {{ source('moonshot_raw', 'agent_messages') }}
),

renamed_messages AS (
    SELECT
        message_id,
        request_id,
        session_id,
        agent_id,
        is_subagent,
        agent_role,
        model AS model_id,
        CAST(REPLACE(ts_utc, 'Z', '') AS TIMESTAMP) AS requested_at_utc,
        CAST(LEFT(ts_local, 19) AS TIMESTAMP) AS requested_at_local,
        CAST(session_part AS INTEGER) AS session_part,
        input_tokens,
        cache_creation_tokens,
        cache_read_tokens,
        output_tokens,
        output_tokens_lower_bound,
        thinking_tokens,
        usage_final AS is_usage_final,
        stop_reason,
        tool_names,
        n_tool_calls,
        n_jsonl_lines,
    FROM source_messages
)

SELECT
    message_id,
    request_id,
    session_id,
    agent_id,
    is_subagent,
    agent_role,
    model_id,
    requested_at_utc,
    requested_at_local,
    session_part,
    input_tokens,
    cache_creation_tokens,
    cache_read_tokens,
    output_tokens,
    output_tokens_lower_bound,
    thinking_tokens,
    is_usage_final,
    stop_reason,
    tool_names,
    n_tool_calls,
    n_jsonl_lines,
FROM renamed_messages
