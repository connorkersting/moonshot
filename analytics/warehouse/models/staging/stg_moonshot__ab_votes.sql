WITH source_ab_votes AS (
    SELECT
        evaluation_id,
        comparison,
        repeat_no,
        newer_version,
        older_version,
        section_no,
        section,
        side_A_version,
        side_B_version,
        side_picked,
        is_tie,
        version_picked,
        newer_outcome,
        is_marginal,
        confidence,
        confidence_rank,
        confidence_raw,
        score_A,
        score_B,
        judge_model,
    FROM {{ source('moonshot_raw', 'ab_votes') }}
),

renamed_ab_votes AS (
    SELECT
        evaluation_id || '-r' || repeat_no || '-s' || section_no AS ab_vote_id,
        evaluation_id,
        comparison AS comparison_label,
        repeat_no,
        'v' || newer_version AS newer_version_id,
        'v' || older_version AS older_version_id,
        section_no,
        section AS section_name,
        'v' || side_A_version AS side_a_version_id,
        'v' || side_B_version AS side_b_version_id,
        side_picked,
        is_tie,
        'v' || version_picked AS picked_version_id,
        newer_outcome,
        is_marginal,
        confidence,
        confidence_rank,
        confidence_raw,
        score_A AS score_a,
        score_B AS score_b,
        judge_model AS judge_model_id,
    FROM source_ab_votes
)

SELECT
    ab_vote_id,
    evaluation_id,
    comparison_label,
    repeat_no,
    newer_version_id,
    older_version_id,
    section_no,
    section_name,
    side_a_version_id,
    side_b_version_id,
    side_picked,
    is_tie,
    picked_version_id,
    newer_outcome,
    is_marginal,
    confidence,
    confidence_rank,
    confidence_raw,
    score_a,
    score_b,
    judge_model_id,
FROM renamed_ab_votes
