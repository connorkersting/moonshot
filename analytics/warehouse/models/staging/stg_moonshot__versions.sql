WITH source_versions AS (
    SELECT
        version,
        version_label,
        src_tag_time,
        final_tag_time,
        export_time,
        progress_logged_time,
        is_best_final,
        duration_s,
        integrated_lufs,
        lra_lu,
        true_peak_dbtp,
        tqc_verdict,
        tqc_black_runs,
        tqc_freeze_runs,
        tqc_click_candidates,
        tqc_flag_count,
        has_qc,
        has_aqc,
        has_tqc,
    FROM {{ source('moonshot_raw', 'versions') }}
),

renamed_versions AS (
    SELECT
        'v' || version AS version_id,
        CAST(version AS INTEGER) AS version_number,
        version_label,
        -- Tag and export times carry a UTC offset (-04:00). Cast through TIMESTAMPTZ
        -- so the offset is applied, then keep both a UTC and a local wall-clock copy.
        CAST(CAST(src_tag_time AS TIMESTAMPTZ) AT TIME ZONE 'UTC' AS TIMESTAMP) AS src_tagged_at_utc,
        CAST(LEFT(src_tag_time, 19) AS TIMESTAMP) AS src_tagged_at_local,
        CAST(CAST(final_tag_time AS TIMESTAMPTZ) AT TIME ZONE 'UTC' AS TIMESTAMP) AS final_tagged_at_utc,
        CAST(LEFT(final_tag_time, 19) AS TIMESTAMP) AS final_tagged_at_local,
        CAST(CAST(export_time AS TIMESTAMPTZ) AT TIME ZONE 'UTC' AS TIMESTAMP) AS exported_at_utc,
        CAST(LEFT(export_time, 19) AS TIMESTAMP) AS exported_at_local,
        -- PROGRESS.md times are naive local times on the agent's own clock.
        CAST(progress_logged_time AS TIMESTAMP) AS progress_logged_at_local,
        is_best_final,
        duration_s,
        integrated_lufs,
        lra_lu AS loudness_range_lu,
        true_peak_dbtp,
        tqc_verdict,
        tqc_black_runs,
        tqc_freeze_runs,
        tqc_click_candidates,
        tqc_flag_count,
        has_qc,
        has_aqc,
        has_tqc,
    FROM source_versions
)

SELECT
    version_id,
    version_number,
    version_label,
    src_tagged_at_utc,
    src_tagged_at_local,
    final_tagged_at_utc,
    final_tagged_at_local,
    exported_at_utc,
    exported_at_local,
    progress_logged_at_local,
    is_best_final,
    duration_s,
    integrated_lufs,
    loudness_range_lu,
    true_peak_dbtp,
    tqc_verdict,
    tqc_black_runs,
    tqc_freeze_runs,
    tqc_click_candidates,
    tqc_flag_count,
    has_qc,
    has_aqc,
    has_tqc,
FROM renamed_versions
